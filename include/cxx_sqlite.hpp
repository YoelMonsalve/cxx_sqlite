        /** statement step - C style, throws exception */
        ErrorCode step()
        {
            ErrorCode ec;
            /* This method is expected to return SQLITE_DONE, or SQLITE_ROW 
             * on success. On other cases (SQLITE_BUSY, ...), throw exception */
            step(ec);
            if (ec != error::done && ec != error::row) {
                throw exception_step(errmsg());
            }
            return ec;
        }
        /* second signature, based on error_code's nomenclature */
        statement & step(ErrorCode &ec) noexcept 
        {
            /* this is the nothrow, `error_code` based version */
            rc_ = sqlite3_step(pStmt);
            ec = rc_;
            return *this;
        }
        const statement & step(ErrorCode &ec) const noexcept 
        {
            /* this is the nothrow, `error_code` based version */
            ec = sqlite3_step(pStmt);
            return *this;
        }

        /** statement reset - C style */
        ErrorCode reset()
        {
            /* method is expected to only return SQLITE_OK on success.
             * Otherwise, throw exception */
            next_bind_col_ = 1;
            last_fetch_state_ = int(error::ok);
            rc_ = sqlite3_reset(pStmt);
            if (rc_ != int(error::ok)) {
                throw exception_reset(errmsg());
            }
            return rc_;
        }
        /* noexcept version, error_code based */
        statement & reset(ErrorCode ec) noexcept 
        {
            next_bind_col_ = 1;
            last_fetch_state_ = int(error::ok);
            ec = sqlite3_reset(pStmt);
            return *this;
        }
        /* noexcept const version, error_code based */
        const statement & reset(ErrorCode ec) const noexcept 
        {
            const_cast<statement*>(this)->next_bind_col_ = 1;
            last_fetch_state_ = int(error::ok);
            ec = sqlite3_reset(pStmt);
            return *this;
        }

        /** 
         * statement finalize 
         * https://www.sqlite.org/c3ref/finalize.html
         * */
        ErrorCode finalize() noexcept
        {
            /* If the most recent evaluation of the statement encountered 
             * no errors or if the statement is never been evaluated, 
             * then sqlite3_finalize() returns SQLITE_OK. 
             * If the most recent evaluation of statement `S` failed, 
             * then sqlite3_finalize(S) returns the appropriate error code 
             * or extended error code. */
            next_bind_col_ = 1;
            last_fetch_state_ = int(error::ok);
            if (pStmt != nullptr)
            {
                rc_ = sqlite3_finalize(pStmt);
                pStmt = nullptr;
            }
            return rc_;
        }

        /** clear all bound parameters */
        ErrorCode clear_bindings() noexcept
        {
            next_bind_col_ = 1;
            if (pStmt != nullptr)
            {
                rc_ = sqlite3_clear_bindings(pStmt);
            }
            return rc_;
        }

        /** check if statement is prepared / valid and not at error or end of fetch stream */
        bool is_valid() const noexcept { return pStmt != nullptr; }
        explicit operator bool() const noexcept {
            if (!is_valid()) return false;
            if (last_fetch_state_ == int(error::done)) return false;
            if (last_fetch_state_ != int(error::ok) && last_fetch_state_ != int(error::row)) return false;
            return true;
        }

        /** Reset sequential parameter stream binding index */
        void reset_bind_cursor() noexcept { next_bind_col_ = 1; }

        /** Stream insertion: execute immediately on cxx_sqlite3::exec / cxx_sqlite3::eol */
        statement &operator<<(exec_t)
        {
            step();
            reset();
            clear_bindings();
            return *this;
        }

        /** Stream insertion: struct / object mapping via ADL to_sqlite */
        template <typename T, typename std::enable_if_t<detail::has_to_sqlite<T>::value &&
                                                        !std::is_same_v<std::decay_t<T>, exec_t>, int> = 0>
        statement &operator<<(const T &val)
        {
            to_sqlite(*this, val);
            return *this;
        }

        /** Stream insertion: sequential positional value binding */
        template <typename T, typename std::enable_if_t<!detail::has_to_sqlite<T>::value &&
                                                        !std::is_same_v<std::decay_t<T>, exec_t>, int> = 0>
        statement &operator<<(const T &val)
        {
            rc_ = bind_one(next_bind_col_++, val);
            if (rc_ != int(error::ok)) {
                throw exception_bind(errmsg());
            }
            return *this;
        }

        /** Stream extraction: whole-row extraction into struct/object via from_sqlite */
        template <typename T, typename std::enable_if_t<detail::has_from_sqlite<T>::value, int> = 0>
        statement &operator>>(T &val)
        {
            ErrorCode ec;
            step(ec);
            last_fetch_state_ = ec;
            if (ec == error::row) {
                row r = read_current_row();
                from_sqlite(r, val);
            } else if (ec == error::done) {
                // End of rows reached; last_fetch_state_ remains error::done so operator bool() returns false
            } else {
                throw exception_step(errmsg());
            }
            return *this;
        }

        /** Stream extraction: whole-row extraction into cxx_sqlite3::row */
        statement &operator>>(row &r)
        {
            ErrorCode ec;
            step(ec);
            last_fetch_state_ = ec;
            if (ec == error::row) {
                r = read_current_row();
            } else if (ec == error::done) {
                r = row{};
            } else {
                throw exception_step(errmsg());
            }
            return *this;
        }

        /** Stream extraction: tuple deconstruction */
        template <typename... Ts>
        statement &operator>>(std::tuple<Ts...> &val)
        {
            ErrorCode ec;
            step(ec);
            last_fetch_state_ = ec;
            if (ec == error::row) {
                row r = read_current_row();
                if (r.size() < sizeof...(Ts)) {
                    throw exception_column("row has fewer columns than requested tuple size");
                }
                val = detail::tuple_from_row_impl<std::tuple<Ts...>>(r, std::index_sequence_for<Ts...>{});
            } else if (ec == error::done) {
                // End of rows reached
            } else {
                throw exception_step(errmsg());
            }
            return *this;
        }

        /**
         * Submit a query for execution. This is similar to the `mysqli::query()` method
         * of the PHP MySQLi library (https://www.php.net/manual/en/mysqli.query.php).
         * Version with arguments.
         */
        template <class... Ts>
        ErrorCode query(const string sql, 
            vector<col_id_t> col_ids, Ts... vals) // throws ...
        {
            ErrorCode ec;
            ec = prepare(sql);
            ec = bind(col_ids, vals...);
            return ec;
        }
        /** Version with no arguments. */
        ErrorCode query(const string sql) // throws ...
        {
            ErrorCode ec;
            ec = prepare(sql);
            return ec;
        }
        /**
         * Fetch the next row of the result set associated with the more
         * recent query.
         */
        typedef row record;          // row = record
        typedef std::vector<record> recordSet;
        typedef recordSet result;    // result = recordSet

        row read_current_row() const
        {
            row r;
            col_index_t n_cols = column_count();
            for (col_index_t j = 0; j < n_cols; j++) {
                const char *col_name = column_name(j);
                data_type_t col_type = column_type(j);
                switch (col_type) {
                case data_type::int_t:
                    r.add(col_name, generic_value(static_cast<int64_t>(sqlite3_column_int64(pStmt, j))));
                    break;
                case data_type::float_t:
                    r.add(col_name, generic_value(sqlite3_column_double(pStmt, j)));
                    break;
                case data_type::text_t: {
                    const unsigned char *txt = sqlite3_column_text(pStmt, j);
                    r.add(col_name, std::string(reinterpret_cast<const char *>(txt ? txt : reinterpret_cast<const unsigned char *>(""))));
                    break;
                }
                case data_type::blob_val: {
                    const void *blob = sqlite3_column_blob(pStmt, j);
                    int bytes = sqlite3_column_bytes(pStmt, j);
                    r.add(col_name, generic_value(blob, bytes > 0 ? static_cast<size_t>(bytes) : 0));
                    break;
                }
                case data_type::null_val:
                default:
                    r.add(col_name, generic_value(nullptr));
                    break;
                }
            }
            return r;
        }

        row fetch_row(ErrorCode &ec)
        {
            row r;
            step(ec);
            CXX_SQLITE3_LOG_DEBUG("step returned: " << ec);
            if (ec != error::row) {
                if (ec == error::done) {
                    reset(ec);
                }
                return r;
            }
            return read_current_row();
        }

        row fetch_row()
        {
            ErrorCode ec;
            return fetch_row(ec);
        }

        /** Input iterator for range-based for loops: for (auto row : stmt) */
        class iterator {
            statement *stmt_ = nullptr;
            row current_row_;
            bool at_end_ = true;

            void advance() {
                if (!stmt_ || !stmt_->is_valid()) {
                    at_end_ = true;
                    return;
                }
                ErrorCode ec;
                stmt_->step(ec);
                if (ec == error::row) {
                    current_row_ = stmt_->read_current_row();
                    at_end_ = false;
                } else {
                    at_end_ = true;
                    if (ec == error::done) {
                        stmt_->reset(ec);
                    }
                }
            }

        public:
            using iterator_category = std::input_iterator_tag;
            using value_type = row;
            using difference_type = std::ptrdiff_t;
            using pointer = const row *;
            using reference = const row &;

            iterator() : stmt_(nullptr), at_end_(true) {}
            explicit iterator(statement *s) : stmt_(s), at_end_(false) {
                advance();
            }

            reference operator*() const { return current_row_; }
            pointer operator->() const { return &current_row_; }

            iterator &operator++() {
                advance();
                return *this;
            }

            bool operator==(const iterator &other) const {
                if (at_end_ && other.at_end_) return true;
                return (at_end_ == other.at_end_) && (stmt_ == other.stmt_);
            }

            bool operator!=(const iterator &other) const {
                return !(*this == other);
            }
        };

        iterator begin() { return iterator(this); }
        iterator end() { return iterator(); }


        /**
         * wrapper for execute: prepare + step + reset + finalize
         */
        template <class... Ts>
        void execute(const char *sql, 
            vector<col_id_t> col_ids, Ts... vals) 
        {
            try {
                prepare(sql);
                bind(col_ids, vals...);
                step();
                reset();
            } catch (exception &e) {
                CXX_SQLITE3_LOG_DEBUG("exception detected in execute: " << e.what());
                finalize();
                throw;
            }
            finalize();
        }
        /** C++ string version, bind arguments */
        template <class... Ts>
        void execute(const string &sql, 
            vector<col_id_t> col_ids, Ts... vals)
        { execute(sql.c_str(), col_ids, vals...); }

        /** C const char * version, no arguments */
        void execute(const char *sql) 
        {
            try {
                prepare(sql);
                step();
                reset();
            } catch (exception &e) {
                CXX_SQLITE3_LOG_DEBUG("exception detected in execute: " << e.what());
                finalize();
                throw;
            }
            finalize();
        }
        /** C++ string version, no arguments */
        inline void execute(const string &sql)
        { execute(sql.c_str()); }        

