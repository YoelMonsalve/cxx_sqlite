#!/usr/bin/env python3
"""
Amalgamation script for cxx_sqlite3 library.
Combines all modular headers in include/ into a single standalone header: include/cxx_sqlite.hpp

Usage:
    python3 scripts/amalgamate.py [-o output_file]
"""

import sys
import os
import re
import argparse

HEADER_ORDER = [
    ("Section A: Environment & C++ Standard Compatibility", "cpp_version.hpp"),
    ("Section B: Error Codes & Categories", "error_code.hpp"),
    ("Section C: Exception Hierarchy & Diagnostics", "exception.hpp"),
    ("Section D: Result & Throwable Abstractions", "throwable.hpp"),
    ("Section E: Basic Types & Constants", "basic_types.hpp"),
    ("Section F: Dynamic Value System (generic_value)", "object.hpp"),
    ("Section G: Serialization & ORM Type Traits", "serializer.hpp"),
    ("Section H: SQLite Database Engine & RAII Core", "sqlite.hpp"),
    ("Section I: User-Defined Functions", "functions.hpp"),
]

SYSTEM_INCLUDE_REGEX = re.compile(r'^\s*#include\s+<([^>]+)>')
LOCAL_INCLUDE_REGEX = re.compile(r'^\s*#include\s+["\']([^"\']+)["\']')
HEADER_GUARD_REGEX = re.compile(r'^\s*#(ifndef|define|endif)\s+([A-Z0-9_]+_HPP_?)')

PREAMBLE_TEMPLATE = """/**
 * =============================================================================
 * CXX_SQLITE.HPP - Singleton Amalgamated Header
 * 
 * -.- The cxx_sqlite3 library (Release 2.0) -.-
 * 
 * High-level, type-safe, modern C++ wrapper for SQLite3.
 * Features:
 *   - RAII resource management (connections, statements, transactions)
 *   - Universal generic_value container (std::variant backed, type-safe)
 *   - Strongly-typed ORM serialization and tuple bindings
 *   - Modern stream operators (<< and >>)
 *   - Configurable implicit/explicit conversion policies
 *   - Standard system_error and rich exception hierarchy
 * 
 * @version 2.0.0
 * @author  Yoel Monsalve | pair-programmer: Gemini AI.
 * @date    2026-10-12
 * 
 * (C) Copyright Yoel Monsalve 2025-2026.
 * Distributed under MIT License.
 * =============================================================================
 * DO NOT EDIT THIS FILE DIRECTLY.
 * This file is automatically generated by scripts/amalgamate.py from modular
 * headers in include/.
 * =============================================================================
 */

#ifndef CXX_SQLITE_HPP_
#define CXX_SQLITE_HPP_

/* Optional user configuration override */
#if __has_include("cxx_sqlite3_config.hpp")
    #include "cxx_sqlite3_config.hpp"
#endif

"""

SECTION_J_INLINES = """/* =========================================================================
 * Section J: Inlined Core Definitions (Header-Only Runtime Support)
 * ========================================================================= */

namespace cxx_sqlite3
{
    /* Error category singleton instance */
    inline const std::error_category &error_category_inst() noexcept {
        static const cxx_sqlite3::error_category ecat{};
        return ecat;
    }

    /* Error code construction */
    inline std::error_code make_error_code(error ev) noexcept {
        return std::error_code(static_cast<int>(ev), error_category_inst());
    }

    inline std::error_code make_error_code(error_code_t ev) noexcept {
        return std::error_code(static_cast<int>(ev), error_category_inst());
    }

    /* Error condition construction */
    inline std::error_condition make_error_condition(error ev) noexcept {
        return std::error_condition(static_cast<int>(ev), error_category_inst());
    }

    inline std::error_condition make_error_condition(error_code_t ev) noexcept {
        return std::error_condition(static_cast<int>(ev), error_category_inst());
    }

    /* Comparison between return_code_t and ErrorCode */
    inline bool operator==(const return_code_t rc, const ErrorCode &ec) noexcept {
        return rc == ec.value();
    }

    inline bool operator!=(const return_code_t rc, const ErrorCode &ec) noexcept {
        return rc != ec.value();
    }
}
"""

def process_headers(include_dir):
    system_includes = set()
    section_contents = []

    for section_title, header_file in HEADER_ORDER:
        header_path = os.path.join(include_dir, header_file)
        if not os.path.exists(header_path):
            raise FileNotFoundError(f"Required header not found: {header_path}")

        with open(header_path, "r", encoding="utf-8") as f:
            lines = f.readlines()

        # Find header guard positions
        first_guard_idx = -1
        second_guard_idx = -1
        last_endif_idx = -1

        for idx, line in enumerate(lines):
            stripped = line.strip()
            if first_guard_idx == -1 and stripped.startswith("#ifndef ") and ("_HPP" in stripped or "_H_" in stripped):
                first_guard_idx = idx
            elif first_guard_idx != -1 and second_guard_idx == -1 and stripped.startswith("#define ") and ("_HPP" in stripped or "_H_" in stripped):
                second_guard_idx = idx
            if stripped.startswith("#endif"):
                last_endif_idx = idx

        cleaned_lines = []
        in_config_hook = False

        for i, line in enumerate(lines):
            # Skip the file-level header guards
            if i in (first_guard_idx, second_guard_idx, last_endif_idx):
                continue

            # Skip redundant cxx_sqlite3_config.hpp hooks inside individual files
            if '__has_include("cxx_sqlite3_config.hpp")' in line:
                in_config_hook = True
                continue
            if in_config_hook:
                if line.strip().startswith("#endif"):
                    in_config_hook = False
                continue

            # Collect system includes
            sys_match = SYSTEM_INCLUDE_REGEX.match(line)
            if sys_match:
                system_includes.add(sys_match.group(1))
                continue

            # Strip local includes (e.g. #include "foo.hpp")
            if LOCAL_INCLUDE_REGEX.match(line):
                continue

            cleaned_lines.append(line)

        # Trim leading and trailing whitespace lines
        content = "".join(cleaned_lines).strip()
        section_contents.append((section_title, header_file, content))

    return system_includes, section_contents

def amalgamate(include_dir, output_path):
    system_includes, sections = process_headers(include_dir)

    # Standard include ordering: standard libraries first, sqlite3.h last
    std_includes = sorted([inc for inc in system_includes if inc != "sqlite3.h"])
    if "sqlite3.h" in system_includes:
        std_includes.append("sqlite3.h")

    out = []
    out.append(PREAMBLE_TEMPLATE)

    # Write deduplicated includes
    out.append("/* System and Third-Party Dependencies */\n")
    for inc in std_includes:
        out.append(f"#include <{inc}>\n")
    out.append("\n")

    # Write each section
    for section_title, header_file, content in sections:
        banner = (
            f"/* =========================================================================\n"
            f" * {section_title} ({header_file})\n"
            f" * ========================================================================= */\n\n"
        )
        out.append(banner)
        out.append(content)
        out.append("\n\n")

    # Write inlined definitions
    out.append(SECTION_J_INLINES)
    out.append("\n#endif /* CXX_SQLITE_HPP_ */\n")

    output_content = "".join(out)

    os.makedirs(os.path.dirname(os.path.abspath(output_path)), exist_ok=True)
    with open(output_path, "w", encoding="utf-8") as f:
        f.write(output_content)

    print(f"[OK] Successfully generated singleton header: {output_path} ({len(output_content.splitlines())} lines)")

def main():
    parser = argparse.ArgumentParser(description="Amalgamate cxx_sqlite3 headers into a single singleton header")
    parser.add_argument("-i", "--include-dir", default="include", help="Path to modular include directory (default: include)")
    parser.add_argument("-o", "--output", default="include/cxx_sqlite.hpp", help="Output path (default: include/cxx_sqlite.hpp)")
    args = parser.parse_args()

    amalgamate(args.include_dir, args.output)

if __name__ == "__main__":
    main()
