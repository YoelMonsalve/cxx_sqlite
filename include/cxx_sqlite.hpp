    /**
     * row
     * Represents a single database row with column name and index access,
     * type-safe extraction via as<T>(), std::optional<T> nullability,
     * and tuple deconstruction (as<Types...>()).
     */
    class row
    {
        std::vector<std::string> col_names_;
        std::vector<generic_value> values_;
        std::map<std::string, size_t> col_indices_;

    public:
        row() = default;

        void add(const std::string &name, const generic_value &val)
        {
            col_indices_[name] = values_.size();
            col_names_.push_back(name);
            values_.push_back(val);
        }

        size_t size() const noexcept { return values_.size(); }
        bool empty() const noexcept { return values_.empty(); }

        bool has_column(const std::string &name) const
        {
            return col_indices_.find(name) != col_indices_.end();
        }

        bool is_null(const std::string &name) const
        {
            auto it = col_indices_.find(name);
            if (it == col_indices_.end()) return true;
            return values_[it->second].is_null();
        }

        bool is_null(size_t index) const
        {
            if (index >= values_.size()) return true;
            return values_[index].is_null();
        }

        const generic_value &operator[](const std::string &name) const
        {
            auto it = col_indices_.find(name);
            if (it == col_indices_.end()) {
                throw exception_column(("column not found: " + name).c_str());
            }
            return values_[it->second];
        }

        const generic_value &operator[](const char *name) const
        {
            return (*this)[std::string(name ? name : "")];
        }

        const generic_value &operator[](size_t index) const
        {
            if (index >= values_.size()) {
                throw exception_column("column index out of range");
            }
            return values_[index];
        }

        template <typename T>
        T get(const std::string &name) const
        {
            return (*this)[name].as<T>();
        }

        template <typename T>
        T get(size_t index) const
        {
            return (*this)[index].as<T>();
        }

        /**
         * Object extraction: row.as<User>()
         * Dispatches via ADL from_sqlite(row, val).
         */
        template <typename T>
        T as() const
        {
            if constexpr (detail::is_tuple<T>::value) {
                constexpr std::size_t N = std::tuple_size_v<T>;
                if (this->size() < N) {
                    throw exception_column("row has fewer columns than requested tuple size");
                }
                return detail::tuple_from_row_impl<T>(*this, std::make_index_sequence<N>{});
            } else if constexpr (detail::has_from_sqlite<T>::value) {
                T obj{};
                adl_serializer<T>::from_sqlite(*this, obj);
                return obj;
            } else if constexpr (std::is_default_constructible_v<T>) {
                if (this->size() == 1) {
                    return (*this)[size_t(0)].template as<T>();
                }
                T obj{};
                adl_serializer<T>::from_sqlite(*this, obj);
                return obj;
            } else {
                static_assert(detail::has_from_sqlite<T>::value,
                    "cxx_sqlite3: Type does not define from_sqlite(const row&, T&) or CXX_SQLITE3_DEFINE_TYPE_NON_INTRUSIVE");
            }
        }

        /**
         * Tuple deconstruction: row.as<std::tuple<int, string, double>>()
         * or row.as<int, string, double>()
         */
        template <typename T1, typename T2, typename... Rest>
        std::tuple<T1, T2, Rest...> as() const
        {
            constexpr std::size_t N = 2 + sizeof...(Rest);
            if (this->size() < N) {
                throw exception_column("row has fewer columns than requested tuple size");
            }
            return detail::tuple_from_row_impl<std::tuple<T1, T2, Rest...>>(
                *this, std::make_index_sequence<N>{}
            );
        }

        const std::vector<std::string> &columns() const noexcept
        {
            return col_names_;
        }

        // Map-style insert for compatibility
        void insert(const std::pair<col_id_t, generic_value> &p)
        {
            add(p.first ? p.first : "", p.second);
        }

        /** Reset sequential column extraction cursor */
        void reset_column_cursor() const noexcept
        {
            next_col_index_ = 0;
        }

        /** Sequential column extraction: row >> var1 >> var2 >> ... */
        template <typename T>
        const row &operator>>(T &target) const
        {
            if (next_col_index_ >= values_.size()) {
                throw exception_column("no more columns available for extraction");
            }
            target = values_[next_col_index_++].template as<T>();
            return *this;
        }

    private:
        mutable size_t next_col_index_ = 0;
    };

    namespace detail {
        template <typename Tuple, std::size_t... Is>
        inline Tuple tuple_from_row_impl(const row &r, std::index_sequence<Is...>) {
            return Tuple{ (r[Is].template as<std::tuple_element_t<Is, Tuple>>())... };
        }
    }

